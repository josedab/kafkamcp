// --- Concurrent StartStream TOCTOU ---

func TestStreamSessionCapacity_ConcurrentRace(t *testing.T) {
	t.Parallel()
	m := &Manager{
		clients: make(map[string]*kgo.Client),
		admins:  make(map[string]*kadm.Client),
		configs: map[string]*config.ClusterConfig{
			"prod": {Name: "prod", BootstrapServers: "localhost:9092", Default: true},
		},
		logger:    slog.Default(),
		defClust:  "prod",
		streamMgr: newStreamSessionManager(),
	}

	// Fill to one below limit
	for i := 0; i < maxSessionsGlobal-1; i++ {
		m.streamMgr.sessions[fmt.Sprintf("s%d", i)] = &StreamSession{
			ID:     fmt.Sprintf("s%d", i),
			Status: "running",
		}
	}

	// Race two requests for the last slot - both will fail at kgo client creation
	// but only one should pass the capacity check
	var wg sync.WaitGroup
	errors := make(chan error, 5)
	for i := 0; i < 5; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			_, err := m.StartStream(context.Background(), "prod", StreamConfig{Topic: "test"})
			if err != nil {
				errors <- err
			}
		}()
	}
	wg.Wait()
	close(errors)

	// At least some should have failed with capacity error
	capacityErrors := 0
	for err := range errors {
		if strings.Contains(err.Error(), "session limit") {
			capacityErrors++
		}
	}
	// With 1 slot and 5 racers, at least 4 should fail with capacity
	if capacityErrors < 1 {
		t.Errorf("expected at least 1 capacity error from 5 racers, got %d", capacityErrors)
	}
}

// --- Config defaults ---

func TestStreamConfigClamping_BatchSize(t *testing.T) {
	t.Parallel()
	// Test at the streamSessionManager level by checking the config defaults
	// applied in StartStream

	tests := []struct {
		name     string
		input    int
		expected int
	}{
		{"zero becomes 10", 0, 10},
		{"negative becomes 10", -5, 10},
		{"normal stays", 50, 50},
		{"over 100 becomes 100", 200, 100},
		{"exactly 100", 100, 100},
		{"exactly 10", 10, 10},
	}

	for _, tt := range tests {
		cfg := StreamConfig{BatchSize: tt.input, Topic: "test"}
		if cfg.BatchSize <= 0 {
			cfg.BatchSize = 10
		}
		if cfg.BatchSize > 100 {
			cfg.BatchSize = 100
		}
		if cfg.BatchSize != tt.expected {
			t.Errorf("%s: got %d, want %d", tt.name, cfg.BatchSize, tt.expected)
		}
	}
}

