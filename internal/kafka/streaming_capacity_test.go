// --- Session capacity limits ---

func TestStreamSessionCapacity_GlobalLimit(t *testing.T) {
	t.Parallel()
	m := &Manager{
		clients: make(map[string]*kgo.Client),
		admins:  make(map[string]*kadm.Client),
		configs: map[string]*config.ClusterConfig{
			"prod": {Name: "prod", BootstrapServers: "localhost:9092", Default: true},
		},
		logger:    slog.Default(),
		defClust:  "prod",
		streamMgr: newStreamSessionManager(),
	}

	// Fill up to global limit
	for i := 0; i < maxSessionsGlobal; i++ {
		m.streamMgr.sessions[fmt.Sprintf("s%d", i)] = &StreamSession{
			ID:     fmt.Sprintf("s%d", i),
			Status: "running",
		}
	}

	// StartStream should fail due to global limit
	_, err := m.StartStream(context.Background(), "prod", StreamConfig{Topic: "test"})
	if err == nil {
		t.Fatal("expected error for global session limit")
	}
	if !strings.Contains(err.Error(), "global streaming session limit") {
		t.Errorf("unexpected error: %v", err)
	}
}

