// --- ControlStream actions ---

func TestControlStream_PauseWithCleanup(t *testing.T) {
	t.Parallel()
	m := testManager()
	session := &StreamSession{
		ID:     "test-session",
		Status: "running",
		cancel: func() {},
	}
	m.streamMgr.sessions["test-session"] = session

	result, err := m.ControlStream("test-session", "pause")
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if result.Status != "paused" {
		t.Errorf("expected paused, got %s", result.Status)
	}
	if !session.paused.Load() {
		t.Error("expected paused flag to be true")
	}
}

